const {contextBridge, ipcRenderer} = require('electron');
const listen = (name, fn) => { ipcRenderer.on(name, (_, value) => fn(value)); };
contextBridge.exposeInMainWorld('mimo', {
  config: () => ipcRenderer.invoke('config'),
  setting: (key,value) => ipcRenderer.invoke('setting',key,value),
  voices: () => ipcRenderer.invoke('voices'),
  perform: action => ipcRenderer.send('perform',action),
  read: title => ipcRenderer.send('read',title),
  onProfile: fn => listen('profile',fn),
  onPerform: fn => listen('perform',fn),
  voiceStatus: fn => listen('voice-status',fn),
  wakeStatus: fn => listen('wake-status',fn),
  schedulerStatus: fn => listen('scheduler-status',fn),
  list: () => ipcRenderer.invoke('list'),
  save: (title,due,id) => ipcRenderer.invoke('save',title,due,id),
  act: (id,action,minutes) => ipcRenderer.invoke('act',id,action,minutes),
  open: () => ipcRenderer.send('open'),
  move: (x,y) => ipcRenderer.send('move',x,y),
  position: () => ipcRenderer.send('position'),
  changed: fn => listen('changed',fn),
  showForm: fn => listen('form',fn),
  showStudio: fn => listen('studio',fn),
  showActions: fn => listen('show-actions',fn),
  listActions: () => ipcRenderer.invoke('list-actions'),
  pinSite: (name,address) => ipcRenderer.invoke('pin-site',name,address),
  pinLocal: kind => ipcRenderer.invoke('pin-local',kind),
  removePin: id => ipcRenderer.invoke('remove-pin',id),
  runAction: (id,text) => ipcRenderer.invoke('run-action',id,text),
  connectAction: (id,key) => ipcRenderer.invoke('connect-action',id,key),
  sendAction: (id,text) => ipcRenderer.invoke('send-action',id,text),
  showWorkflows: fn => listen('show-workflows',fn),
  showAgent: fn => listen('show-agent',fn),
  agentProgress: fn => listen('agent-progress',fn),
  agentConfig: () => ipcRenderer.invoke('agent-config'),
  agentSettings: value => ipcRenderer.invoke('agent-settings',value),
  agentPlan: text => ipcRenderer.invoke('agent-plan',text),
  agentRun: (id,chosen) => ipcRenderer.invoke('agent-run',id,chosen),
  agentStop: () => ipcRenderer.invoke('agent-stop'),
  agentForget: () => ipcRenderer.invoke('agent-forget'),
  talk: () => ipcRenderer.send('talk'),
  closeCompanion: () => ipcRenderer.send('close-companion'),
  workflowProgress: fn => listen('workflow-progress',fn),
  workflows: () => ipcRenderer.invoke('workflow-config'),
  workflowConnect: value => ipcRenderer.invoke('workflow-connect',value),
  workflowDisconnect: () => ipcRenderer.invoke('workflow-disconnect'),
  workflowSave: value => ipcRenderer.invoke('workflow-save',value),
  workflowRemove: id => ipcRenderer.invoke('workflow-remove',id),
  workflowRun: (id,text) => ipcRenderer.invoke('workflow-run',id,text),
  workflowStop: id => ipcRenderer.invoke('workflow-stop',id),
  workflowTemplate: () => ipcRenderer.invoke('workflow-template'),
  conversation: fn => listen('conversation',fn),
  submit: (text,replace) => ipcRenderer.send('submit-turn',text,replace),
  action: (action,value) => ipcRenderer.send('turn-action',action,value),
  stopAudio: () => ipcRenderer.send('stop-audio'),
  startMic: () => ipcRenderer.send('start-mic'),
  micConsent: enabled => ipcRenderer.invoke('mic-consent',enabled),
  focusWidget: () => ipcRenderer.send('focus-widget')
});
